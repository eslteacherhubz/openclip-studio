"""Tests for review items and mock-provider plan integration."""

from __future__ import annotations

import json
from pathlib import Path

from openclip.ai import (
    MockAIProvider,
    ReviewStatus,
    load_provider_config,
    normalize_ai_plan,
    parse_ai_plan,
    plan_to_review_items,
)

FIXTURE = Path(__file__).parent / "fixtures" / "ai" / "mock_plan.json"


def _fixture_plan() -> object:
    return parse_ai_plan(json.loads(FIXTURE.read_text(encoding="utf-8")))


class TestReviewItems:
    def test_all_kinds_become_items(self) -> None:
        from openclip.ai import AIDirectorPlan

        plan = _fixture_plan()
        assert isinstance(plan, AIDirectorPlan)
        items = plan_to_review_items(plan)
        kinds = {item.kind for item in items}
        assert kinds == {"clip", "cut", "caption", "broll", "zoom"}
        assert len(items) == 2 + 2 + 2 + 1 + 1

    def test_all_items_default_pending(self) -> None:
        items = plan_to_review_items(_fixture_plan())  # type: ignore[arg-type]
        assert all(item.status == ReviewStatus.PENDING for item in items)

    def test_reasons_preserved(self) -> None:
        items = plan_to_review_items(_fixture_plan())  # type: ignore[arg-type]
        by_id = {item.id: item for item in items}
        assert by_id["clip-intro"].reason == "Strong opening line, sets context"
        assert by_id["cut-filler"].reason == "filler words and pause"

    def test_ids_deterministic_and_sorted(self) -> None:
        first = plan_to_review_items(_fixture_plan())  # type: ignore[arg-type]
        second = plan_to_review_items(_fixture_plan())  # type: ignore[arg-type]
        assert [i.to_dict() for i in first] == [i.to_dict() for i in second]
        starts = [i.start_seconds for i in first]
        assert starts == sorted(starts)

    def test_payload_contains_original_item(self) -> None:
        items = plan_to_review_items(_fixture_plan())  # type: ignore[arg-type]
        clip = next(i for i in items if i.kind == "clip" and i.id == "clip-example")
        assert clip.payload["title"] == "Key example"
        assert clip.payload["span"] == {"start_seconds": 40.0, "end_seconds": 55.0}
        assert clip.end_seconds == 55.0


class TestMockIntegration:
    def test_mock_output_parses_as_plan(self) -> None:
        provider = MockAIProvider(load_provider_config("local_mock", env={}))
        raw = provider.complete("Make a highlight reel")
        plan = parse_ai_plan(json.loads(raw))
        assert plan.provider == "local_mock"
        assert plan.prompt == "Make a highlight reel"
        assert len(plan.clips) == 1
        assert len(plan.cuts) == 1
        assert len(plan.captions) == 1

    def test_normalized_mock_plan_converts_to_review_items(self) -> None:
        provider = MockAIProvider(load_provider_config("local_mock", env={}))
        plan = normalize_ai_plan(parse_ai_plan(json.loads(provider.complete("edit this"))))
        items = plan_to_review_items(plan)
        assert {i.kind for i in items} == {"clip", "cut", "caption"}
        assert all(i.status == ReviewStatus.PENDING for i in items)
        assert all(i.id for i in items)  # IDs generated by normalization
